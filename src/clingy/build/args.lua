-- Generates the typed `args` module of a built CLI. For every command it
-- declares LuaLS classes for the parsed values (`ctx.args`) and the handler
-- context, plus a table of result keys for `ctx:get(...)`. At run time the
-- keys are plain strings, which `ctx:get` already accepts, so handlers never
-- need the declaration (and the DSL and schema library behind it).
--
-- Typing goes through concrete classes because LuaLS does not infer the
-- generic in `clingy.Binding<O>`: `ctx.args.name` is typed, `ctx:get(...)`
-- is not.

local adapter = require("clingy.adapter")
local serialize = require("clingy.build.serialize")

local M = {}

local function quote(v)
  if type(v) == "string" then return string.format("%q", v) end
  return tostring(v)
end

local function schema_type(binding)
  if binding.form then return "table" end
  if binding.schema == nil then return "string" end
  local info = adapter.inspect_schema(binding.schema)
  local kind = info.kind
  if kind == "string" or kind == "integer" or kind == "number" or kind == "boolean" then
    if info.options and #info.options > 0 then
      local values = {}
      for i, option in ipairs(info.options) do values[i] = quote(option) end
      return table.concat(values, "|")
    end
    return kind
  end
  if kind == "picklist" and info.options and #info.options > 0 then
    local values = {}
    for i, option in ipairs(info.options) do values[i] = quote(option) end
    return table.concat(values, "|")
  end
  return "any"
end

local function binding_type(binding)
  if binding.kind == "flag" then return "boolean" end
  if binding.kind == "passthrough" or binding.kind == "end" then return "string[]" end
  local t = schema_type(binding)
  if binding.aggregate == "array" then t = "(" .. t .. ")[]" end
  local required = (binding.occurrence and (binding.occurrence.min or 0) > 0) or binding.default ~= nil
  if not required then t = t .. "|nil" end
  return t
end

local function name(k)
  if serialize.is_identifier(k) then return k end
  return string.format("[%q]", k)
end

-- "root" stays "root"; "root.remote.add" becomes "remote_add".
local function command_name(node_id)
  if node_id == "root" then return "root" end
  return (node_id:gsub("^root%.", ""):gsub("[^%w_]", "_"))
end

---@param router table A compiled router (clingy.router).
---@param module string The args module's name, used for class names.
---@return string source
function M.generate(router, module)
  local class = module:gsub("[^%w_%.]", "_")
  local commands, by_name = {}, {}
  for _, id in ipairs(serialize.sorted_keys(router.nodes)) do
    local node = router.nodes[id]
    local command = command_name(id)
    if by_name[command] then
      error(("commands %s and %s both map to args.%s"):format(by_name[command], id, command), 0)
    end
    by_name[command] = id
    local fields, seen = {}, {}
    local function add(binding)
      local key = binding.result_key
      if key and not seen[key] then
        seen[key] = true
        fields[#fields + 1] = { key = key, type = binding_type(binding) }
      end
    end
    for _, binding in ipairs(node.declarations_order or {}) do add(binding) end
    for _, option in ipairs(serialize.sorted_keys(node.inherited_options_by_name or {})) do
      add(node.inherited_options_by_name[option])
    end
    table.sort(fields, function(a, b) return a.key < b.key end)
    commands[#commands + 1] = { name = command, id = id, fields = fields }
  end

  local lines = {
    "-- @generated by clingy.build; do not edit.",
    "-- Per command: parsed value types, a handler context type, and result keys.",
    "---@diagnostic disable: assign-type-mismatch",
    "",
  }
  for _, command in ipairs(commands) do
    local base = class .. "." .. command.name
    lines[#lines + 1] = ("---Parsed values of `%s`."):format(command.id)
    lines[#lines + 1] = ("---@class %s.values"):format(base)
    for _, field in ipairs(command.fields) do
      lines[#lines + 1] = ("---@field %s %s"):format(name(field.key), field.type)
    end
    lines[#lines + 1] = ""
    lines[#lines + 1] = ("---Handler context of `%s`: annotate handlers with `---@param ctx %s.context`."):format(command.id, base)
    lines[#lines + 1] = ("---@class %s.context: clingy.Context"):format(base)
    lines[#lines + 1] = ("---@field args %s.values"):format(base)
    lines[#lines + 1] = ""
    lines[#lines + 1] = ("---Result keys of `%s`, for ctx:get(...)."):format(command.id)
    lines[#lines + 1] = ("---@class %s"):format(base)
    for _, field in ipairs(command.fields) do
      lines[#lines + 1] = ("---@field %s clingy.Binding<%s>"):format(name(field.key), field.type)
    end
    lines[#lines + 1] = ""
  end
  lines[#lines + 1] = "---@class " .. class
  for _, command in ipairs(commands) do
    lines[#lines + 1] = ("---@field %s %s.%s"):format(name(command.name), class, command.name)
  end
  lines[#lines + 1] = "local args = {"
  for _, command in ipairs(commands) do
    local keys = {}
    for i, field in ipairs(command.fields) do keys[i] = ("%s = %q"):format(name(field.key), field.key) end
    lines[#lines + 1] = ("  %s = { %s },"):format(name(command.name), table.concat(keys, ", "))
  end
  lines[#lines + 1] = "}"
  lines[#lines + 1] = ""
  lines[#lines + 1] = "return args"
  return table.concat(lines, "\n") .. "\n"
end

return M
