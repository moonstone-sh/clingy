-- Build step: compile the declaration once and write the compiled router as
-- a plain Lua data module. Functions and schemas must be exports of a runtime
-- module; they are written as require references. Anything else that is
-- not plain data fails the build.
local compiler = require("clingy.compiler")
local adapter = require("clingy.adapter")
local runtime_modules, declaration, out = { "greet.handlers", "greet.schemas" }, "greet.cli", "greet/graph.lua"

local refs = {}
for _, m in ipairs(runtime_modules) do
  for k, v in pairs(require(m)) do refs[v] = ("require(%q)[%q]"):format(m, k) end
end

-- Spike-only: the compiler deep-copies declarations, schemas included. Keep
-- runtime-module exports by identity so they stay referenceable.
local util = require("clingy.util")
local deep_copy = util.deep_copy
util.deep_copy = function(value, seen)
  if refs[value] then return value end
  return deep_copy(value, seen)
end
local router = compiler.compile(require(declaration))   -- validate_graph runs here, at build time

-- Precompute what coercion used to reflect from Valua on every value.
local coerce, seen_schema = {}, {}
local function sorted_keys(t)
  local keys = {}
  for k in pairs(t) do keys[#keys + 1] = k end
  table.sort(keys, function(a, b)
    if type(a) ~= type(b) then return type(a) < type(b) end
    if type(a) == "table" or type(a) == "function" or type(a) == "boolean" then return tostring(a) < tostring(b) end
    return a < b
  end)
  return keys
end
local function find_schemas(t, visited)
  if type(t) ~= "table" or visited[t] then return end
  visited[t] = true
  if refs[t] then
    if not seen_schema[t] and t["~standard"] then
      seen_schema[t] = true
      coerce[#coerce + 1] = { t, adapter.inspect_schema(t).kind or "unknown" }
    end
    return
  end
  for _, k in ipairs(sorted_keys(t)) do find_schemas(t[k], visited) end
end
find_schemas(router, {})
table.sort(coerce, function(a, b) return refs[a[1]] < refs[b[1]] end)

local built = { format = "clingy.built-router.v0", router = router, coerce = coerce }

-- Serializer: shared and cyclic tables are hoisted into T[i], the rest inlined.
local count, order, dropped = {}, {}, {}
local function scan(v, path)
  local tv = type(v)
  if tv == "function" or tv == "userdata" or tv == "thread" then
    if refs[v] then return end
    error(("build: %s at %s is not an export of a runtime module (%s)"):format(tv, path, table.concat(runtime_modules, ", ")), 0)
  end
  if tv ~= "table" or refs[v] then return end
  count[v] = (count[v] or 0) + 1
  if count[v] > 1 then return end
  order[#order + 1] = v
  if getmetatable(v) then error("build: table with a metatable at " .. path, 0) end
  for _, k in ipairs(sorted_keys(v)) do
    if type(k) == "table" or type(k) == "function" then
      dropped[path] = (dropped[path] or 0) + 1   -- identity keys (decl_map) cannot be data
    else
      scan(v[k], path .. "." .. tostring(k))
    end
  end
end
scan(built, "built")

local id, n = {}, 0
for _, t in ipairs(order) do if count[t] > 1 then n = n + 1; id[t] = n end end

local value
local function key(k)
  if type(k) == "string" and k:match("^[%a_][%w_]*$") then return k end
  return "[" .. value(k) .. "]"
end
local function constructor(t)
  local parts = {}
  for _, k in ipairs(sorted_keys(t)) do
    if type(k) ~= "table" and type(k) ~= "function" then parts[#parts + 1] = key(k) .. "=" .. value(t[k]) end
  end
  return "{" .. table.concat(parts, ",") .. "}"
end
function value(v)
  local tv = type(v)
  if refs[v] then return refs[v] end
  if tv == "string" then return ("%q"):format(v) end
  if tv == "number" then
    if v == math.floor(v) and math.abs(v) < 2 ^ 53 then return ("%d"):format(v) end
    return ("%.17g"):format(v)
  end
  if tv == "boolean" or tv == "nil" then return tostring(v) end
  if id[v] then return "T[" .. id[v] .. "]" end
  return constructor(v)
end

local lines = { "-- @generated by build.lua from " .. declaration .. "; do not edit.", 
  "local T={} for i=1," .. n .. " do T[i]={} end" }
for _, t in ipairs(order) do
  if id[t] then
    for _, k in ipairs(sorted_keys(t)) do if type(k) ~= "table" and type(k) ~= "function" then lines[#lines + 1] = "T[" .. id[t] .. "]" .. (key(k):sub(1, 1) == "[" and key(k) or "." .. key(k)) .. "=" .. value(t[k]) end end
  end
end
local nd = 0
for _, n in pairs(dropped) do nd = nd + n end
if nd > 0 then print(("dropped %d identity-keyed entries (ctx:get(decl) lookups)"):format(nd)) end
lines[#lines + 1] = "return " .. value(built)
local f = assert(io.open(out, "w"))
f:write(table.concat(lines, "\n"), "\n")
f:close()
print(("built %s: %d shared tables, %d bytes"):format(out, n, #table.concat(lines, "\n")))
